/**
 * Panda CSS configuration for the FlashBeat Web Studio.
 *
 * - The color system, recipes and conditions come from Park UI
 *   (`src/theme/**`), generated by `npx @park-ui/cli init` / `add`.
 * - `include` covers the actual source directories of this Void app.
 * - `compilerOptions` mirrors `tsconfig.json` so Panda and Park UI resolve the
 *   same `@/*` alias.
 *
 * Imports are relative on purpose: Panda bundles this config file and cannot
 * resolve the `@/*` alias inside it.
 */
export default defineConfig({
  presets: ["@pandacss/preset-base", "@pandacss/preset-panda"],
  jsxFramework: "react",
  preflight: true,
  outdir: "styled-system",
  cwd: ".",

  include: [
    "./src/**/*.{ts,tsx}",
    "./pages/**/*.{ts,tsx}",
    "./routes/**/*.{ts,tsx}",
    "./components/**/*.{ts,tsx}",
    "./db/**/*.{ts,tsx}",
  ],

  exclude: [],

  compilerOptions: {
    baseUrl: ".",
    paths: {
      "@/*": ["./src/*"],
    },
  },

  /**
   * Park UI ships its own color system (slate neutrals + one accent palette).
   * Drop Panda's default 50-950 shades so the app only exposes the palettes
   * defined in `src/theme/colors/**` — the Pen v5 mapping recorded in
   * `docs/design/web-token-mapping.md`.
   */
  plugins: [
    {
      name: "Remove Panda preset colors",
      hooks: {
        "preset:resolved": ({ utils, preset, name }) =>
          name === "@pandacss/preset-panda"
            ? utils.omit(preset, ["theme.tokens.colors", "theme.semanticTokens.colors"])
            : preset,
      },
    },
  ],

  theme: {
    colorPalette: {
      include: ["gray", "blue", "red", "green", "amber"],
    },
    extend: {
      animationStyles: animationStyles,
      recipes: {
        ...recipes,
        // Panda only emits the CSS of a recipe it can see being used. The
        // Park UI components are namespaced (`<Tabs.Root>`), so the default
        // `capitalize(recipe.name)` hint never matches. These hints keep the
        // slot recipes in the stylesheet.
        group: { ...recipes.group, jsx: [/^Group$/] },
        icon: { ...recipes.icon, jsx: [/^Icon$/] },
        spinner: { ...recipes.spinner, jsx: [/^Spinner$/] },
        absoluteCenter: { ...recipes.absoluteCenter, jsx: [/^AbsoluteCenter$/] },
      },
      slotRecipes: {
        ...slotRecipes,
        tabs: { ...slotRecipes.tabs, jsx: [/^Tabs\./] },
        dialog: { ...slotRecipes.dialog, jsx: [/^Dialog\./] },
        field: { ...slotRecipes.field, jsx: [/^Field\./] },
        select: { ...slotRecipes.select, jsx: [/^Select\./] },
        toast: { ...slotRecipes.toast, jsx: [/^Toaster$/] },
      },
      keyframes: keyframes,
      layerStyles: layerStyles,
      textStyles: textStyles,

      tokens: {
        colors: colors,
        durations: durations,
        zIndex: zIndex,
      },

      semanticTokens: {
        colors: {
          fg: {
            default: {
              value: {
                _light: "{colors.gray.12}",
                _dark: "{colors.gray.12}",
              },
            },

            muted: {
              value: {
                _light: "{colors.gray.11}",
                _dark: "{colors.gray.11}",
              },
            },

            subtle: {
              value: {
                _light: "{colors.gray.10}",
                _dark: "{colors.gray.10}",
              },
            },
          },

          border: {
            value: {
              _light: "{colors.gray.4}",
              _dark: "{colors.gray.6}",
            },
          },

          error: {
            value: {
              _light: "{colors.red.9}",
              _dark: "{colors.red.9}",
            },
          },

          /**
           * Application canvas. Pen v5 `bg #1B1B1B`; the recessed surfaces
           * (panels, lists) sit on `gray.1` (Pen `well #131313`).
           */
          canvas: {
            value: {
              _light: "{colors.gray.2}",
              _dark: "{colors.gray.2}",
            },
          },

          blue: blue,
          amber: amber,
          gray: gray,
          red: red,
          green: green,
        },

        shadows: shadows,

        radii: {
          l1: {
            value: "{radii.xs}",
          },

          l2: {
            value: "{radii.sm}",
          },

          l3: {
            value: "{radii.md}",
          },
        },
      },
    },
  },

  globalCss: globalCss,
  conditions: conditions,
});
